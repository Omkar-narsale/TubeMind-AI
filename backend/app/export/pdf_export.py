logger = logging.getLogger("app.export.pdf")

# Register Unicode TrueType font if available on system
FONT_NAME = "Helvetica"

def _register_unicode_font() -> str:
    global FONT_NAME
    possible_fonts = [
        ("Nirmala", "C:/Windows/Fonts/Nirmala.ttc"),
        ("SegoeUI", "C:/Windows/Fonts/segoeui.ttf"),
        ("Arial", "C:/Windows/Fonts/arial.ttf"),
    ]
    for font_alias, font_path in possible_fonts:
        if os.path.exists(font_path):
            try:
                pdfmetrics.registerFont(TTFont(font_alias, font_path))
                FONT_NAME = font_alias
                logger.info(f"Registered PDF font: {font_alias} ({font_path})")
                return FONT_NAME
            except Exception as e:
                logger.warning(f"Failed to register font {font_path}: {e}")
    return "Helvetica"

# Initialize font on module load
_register_unicode_font()


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to add 'Generated by TubeMind AI | Page X of Y' footer."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont(FONT_NAME, 8)
        self.setFillColor(colors.HexColor("#64748b"))
        
        # Draw header separator line
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        
        # Footer text
        footer_left = "Generated by TubeMind AI"
        footer_right = f"Page {self._pageNumber} of {page_count}"
        
        self.drawString(54, 36, footer_left)
        self.drawRightString(612 - 54, 36, footer_right)
        
        self.restoreState()


def generate_pdf(
    video_title: str,
    youtube_url: str,
    feature: str,
    language: str,
    content: str,
) -> bytes:
    """Generates a clean, professional PDF document from learning content."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        "PDFTitle",
        parent=styles["Normal"],
        fontName=FONT_NAME,
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#0f172a"),
        bold=True,
    )

    h1_style = ParagraphStyle(
        "PDFH1",
        parent=styles["Normal"],
        fontName=FONT_NAME,
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=12,
        spaceAfter=6,
        bold=True,
    )

    h2_style = ParagraphStyle(
        "PDFH2",
        parent=styles["Normal"],
        fontName=FONT_NAME,
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#334155"),
        spaceBefore=10,
        spaceAfter=4,
        bold=True,
    )

    body_style = ParagraphStyle(
        "PDFBody",
        parent=styles["Normal"],
        fontName=FONT_NAME,
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#334155"),
        spaceAfter=6,
    )

    bullet_style = ParagraphStyle(
        "PDFBullet",
        parent=styles["Normal"],
        fontName=FONT_NAME,
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#334155"),
        leftIndent=16,
        spaceAfter=4,
    )

    meta_label_style = ParagraphStyle(
        "PDFMetaLabel",
        fontName=FONT_NAME,
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#64748b"),
        bold=True,
    )

    meta_val_style = ParagraphStyle(
        "PDFMetaVal",
        fontName=FONT_NAME,
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#1e293b"),
    )

    story = []

    # 1. Header Banner
    feature_title = feature.replace("-", " ").replace("_", " ").title()
    story.append(Paragraph(f"TubeMind AI &bull; {feature_title}", title_style))
    story.append(Spacer(1, 8))

    # Metadata Table
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    meta_data = [
        [Paragraph("Video Title:", meta_label_style), Paragraph(video_title or "N/A", meta_val_style)],
        [Paragraph("YouTube URL:", meta_label_style), Paragraph(youtube_url or "N/A", meta_val_style)],
        [Paragraph("Language:", meta_label_style), Paragraph(language or "English", meta_val_style)],
        [Paragraph("Date & Time:", meta_label_style), Paragraph(now_str, meta_val_style)],
    ]
    t = Table(meta_data, colWidths=[90, 414])
    t.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ("PADDING", (0, 0), (-1, -1), 4),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ])
    )
    story.append(t)
    story.append(Spacer(1, 14))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=14))

    # 2. Body Parsing (Markdown elements)
    lines = content.split("\n")
    for line in lines:
        raw = line.strip()
        if not raw:
            story.append(Spacer(1, 4))
            continue

        # Format inline bold **text** to HTML <b>text</b> for ReportLab
        formatted_line = raw.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        import re
        formatted_line = re.sub(r'\*\*(.*?)\*\*', r'<b>\1</b>', formatted_line)
        formatted_line = re.sub(r'`(.*?)`', r'<font face="Courier">\1</font>', formatted_line)

        if raw.startswith("# "):
            clean_text = formatted_line.lstrip("# ").strip()
            story.append(Paragraph(clean_text, h1_style))
        elif raw.startswith("## "):
            clean_text = formatted_line.lstrip("# ").strip()
            story.append(Paragraph(clean_text, h2_style))
        elif raw.startswith("### "):
            clean_text = formatted_line.lstrip("# ").strip()
            story.append(Paragraph(clean_text, h2_style))
        elif raw.startswith("- ") or raw.startswith("* ") or raw.startswith("✓ "):
            clean_text = formatted_line[2:].strip()
            story.append(Paragraph(f"&bull; {clean_text}", bullet_style))
        else:
            story.append(Paragraph(formatted_line, body_style))

    doc.build(story, canvasmaker=NumberedCanvas)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
