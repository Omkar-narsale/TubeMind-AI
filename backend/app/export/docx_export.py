import io
import datetime
import re
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT


def generate_docx(
    video_title: str,
    youtube_url: str,
    feature: str,
    language: str,
    content: str,
) -> bytes:
    """Generates a clean, professional Microsoft Word (.docx) document."""
    doc = Document()

    # Set page margins (0.75 in)
    sections = doc.sections
    for section in sections:
        section.top_margin = Inches(0.75)
        section.bottom_margin = Inches(0.75)
        section.left_margin = Inches(0.75)
        section.right_margin = Inches(0.75)

    # 1. Header Banner
    title_p = doc.add_paragraph()
    title_run = title_p.add_run("TubeMind AI")
    title_run.font.name = "Arial"
    title_run.font.size = Pt(22)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(15, 23, 42)

    feature_title = feature.replace("-", " ").replace("_", " ").title()
    sub_run = title_p.add_run(f" — {feature_title}")
    sub_run.font.name = "Arial"
    sub_run.font.size = Pt(16)
    sub_run.font.color.rgb = RGBColor(71, 85, 105)

    # 2. Metadata Table
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    table = doc.add_table(rows=4, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False

    metadata = [
        ("Video Title:", video_title or "N/A"),
        ("YouTube URL:", youtube_url or "N/A"),
        ("Language:", language or "English"),
        ("Date & Time:", now_str),
    ]

    for idx, (label, val) in enumerate(metadata):
        row = table.rows[idx]
        
        # Label cell
        cell_lbl = row.cells[0]
        cell_lbl.width = Inches(1.5)
        p_lbl = cell_lbl.paragraphs[0]
        r_lbl = p_lbl.add_run(label)
        r_lbl.font.bold = True
        r_lbl.font.size = Pt(9.5)
        r_lbl.font.color.rgb = RGBColor(100, 116, 139)

        # Value cell
        cell_val = row.cells[1]
        cell_val.width = Inches(5.0)
        p_val = cell_val.paragraphs[0]
        r_val = p_val.add_run(val)
        r_val.font.size = Pt(9.5)
        r_val.font.color.rgb = RGBColor(30, 41, 59)

    doc.add_paragraph()  # Spacer

    # Divider line
    div_p = doc.add_paragraph()
    div_p.paragraph_format.space_after = Pt(12)

    # 3. Body Content Parsing
    lines = content.split("\n")
    for line in lines:
        raw = line.strip()
        if not raw:
            continue

        if raw.startswith("# "):
            text = raw.lstrip("# ").strip()
            h = doc.add_heading(level=1)
            h.paragraph_format.space_before = Pt(12)
            h.paragraph_format.space_after = Pt(4)
            _add_formatted_runs(h, text, font_size=14, color_rgb=RGBColor(30, 41, 59))
        elif raw.startswith("## "):
            text = raw.lstrip("# ").strip()
            h = doc.add_heading(level=2)
            h.paragraph_format.space_before = Pt(10)
            h.paragraph_format.space_after = Pt(3)
            _add_formatted_runs(h, text, font_size=12, color_rgb=RGBColor(51, 65, 85))
        elif raw.startswith("### "):
            text = raw.lstrip("# ").strip()
            h = doc.add_heading(level=3)
            h.paragraph_format.space_before = Pt(8)
            h.paragraph_format.space_after = Pt(2)
            _add_formatted_runs(h, text, font_size=11, color_rgb=RGBColor(71, 85, 105))
        elif raw.startswith("- ") or raw.startswith("* ") or raw.startswith("✓ "):
            text = raw[2:].strip()
            p = doc.add_paragraph(style='List Bullet')
            p.paragraph_format.space_after = Pt(3)
            _add_formatted_runs(p, text, font_size=10.5)
        else:
            p = doc.add_paragraph()
            p.paragraph_format.space_after = Pt(4)
            _add_formatted_runs(p, raw, font_size=10.5)

    # 4. Footer
    for section in doc.sections:
        footer = section.footer
        f_p = footer.paragraphs[0]
        f_p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        f_run = f_p.add_run("Generated by TubeMind AI")
        f_run.font.size = Pt(8.5)
        f_run.font.color.rgb = RGBColor(148, 163, 184)

    buffer = io.BytesIO()
    doc.save(buffer)
    docx_bytes = buffer.getvalue()
    buffer.close()
    return docx_bytes


def _add_formatted_runs(paragraph, text: str, font_size=10.5, color_rgb=None):
    """Helper to parse markdown **bold** text and add formatted Word runs."""
    parts = re.split(r'(\*\*.*?\*\*)', text)
    for part in parts:
        if part.startswith("**") and part.endswith("**"):
            bold_text = part[2:-2]
            run = paragraph.add_run(bold_text)
            run.font.bold = True
        else:
            run = paragraph.add_run(part)
        
        run.font.name = "Arial"
        run.font.size = Pt(font_size)
        if color_rgb:
            run.font.color.rgb = color_rgb
