import datetime


def generate_markdown(
    video_title: str,
    youtube_url: str,
    feature: str,
    language: str,
    content: str,
) -> bytes:
    """Generates clean GitHub-compatible Markdown document with metadata headers."""
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    feature_title = feature.replace("-", " ").replace("_", " ").title()

    header_block = (
        f"# {feature_title}\n\n"
        f"- **Video Title**: {video_title or 'N/A'}\n"
        f"- **YouTube URL**: {youtube_url or 'N/A'}\n"
        f"- **Language**: {language or 'English'}\n"
        f"- **Export Date**: {now_str}\n"
        f"- **Generated By**: TubeMind AI\n\n"
        f"---\n\n"
    )

    full_md = header_block + content.strip() + "\n"
    return full_md.encode("utf-8")
